export function getCourseMissions(courseId) {
  return COURSE_MISSIONS[courseId] ?? []
}

export function getCourseMissionById(id) {
  for (const missions of Object.values(COURSE_MISSIONS)) {
    const found = missions.find((m) => m.id === id)
    if (found) return found
  }
  return null
}
